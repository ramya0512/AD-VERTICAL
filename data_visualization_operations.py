import pandas as pd
import matplotlib.pyplot as plt

# Step 1: Load the dataset
df = pd.read_csv("covid dataset - Sheet1.csv")

print("COVID-19 DATASET")
print(df)

# 1. BAR CHART - Confirmed Cases by Country

country_cases = df.groupby("Country")["Confirmed"].max()

plt.figure(figsize=(8, 5))
country_cases.plot(kind="bar")
plt.title("COVID-19 Confirmed Cases by Country")
plt.xlabel("Country")
plt.ylabel("Confirmed Cases")
plt.xticks(rotation=0)
plt.show()

# 2. LINE CHART - Confirmed Cases Over Time

plt.figure(figsize=(8, 5))

for country in df["Country"].unique():
    data = df[df["Country"] == country]
    plt.plot(data["Date"], data["Confirmed"], marker="o", label=country)

plt.title("COVID-19 Confirmed Cases Over Time")
plt.xlabel("Date")
plt.ylabel("Confirmed Cases")
plt.legend()
plt.xticks(rotation=45)
plt.show()

# 3. SCATTER PLOT - Confirmed Cases vs Deaths

plt.figure(figsize=(8, 5))
plt.scatter(df["Confirmed"], df["Deaths"])

plt.title("Confirmed Cases vs Deaths")
plt.xlabel("Confirmed Cases")
plt.ylabel("Deaths")
plt.show()

#4. PIE CHART - Deaths by Country
# ------------------------------------------------

country_deaths = df.groupby("Country")["Deaths"].max()

plt.figure(figsize=(7, 7))
plt.pie(
    country_deaths,
    labels=country_deaths.index,
    autopct="%1.1f%%"
)
plt.title("COVID-19 Deaths by Country")
plt.show()

